-- Nexus Plus Premium billing foundation.
-- Razorpay secrets/webhook signing secrets must remain server-side.
-- Run this migration in the Supabase project.

create table if not exists public.subscription_plans (
  plan_id bigint generated by default as identity primary key,
  plan_code text unique not null,
  plan_name text not null,
  tier_level integer not null check (tier_level between 1 and 3),
  description text,
  price_inr numeric(10,2) not null check (price_inr >= 0),
  duration_days integer not null check (duration_days > 0),
  blocks_ads boolean not null default true,
  unlocks_premium_features boolean not null default false,
  is_auto_pay_supported boolean not null default true,
  razorpay_plan_id text unique,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.subscription_plans enable row level security;
drop policy if exists "public can read active subscription plans" on public.subscription_plans;
create policy "public can read active subscription plans"
  on public.subscription_plans
  for select
  to anon, authenticated
  using (is_active = true);

