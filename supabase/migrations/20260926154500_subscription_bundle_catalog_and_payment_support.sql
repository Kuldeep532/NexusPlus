-- Subscription bundles let users buy more monthly credits upfront.
-- Existing subscription_plans remains the canonical entitlement table for the original 3 plans.

create table if not exists public.subscription_credit_bundles (
  bundle_id bigint generated by default as identity primary key,
  bundle_code text not null unique,
  bundle_name text not null,
  duration_days integer not null default 30 check(duration_days>0),
  price_inr numeric not null check(price_inr>0),
  included_credits integer not null check(included_credits>0),
  tier_level integer not null check(tier_level between 1 and 3),
  blocks_ads boolean not null default true,
  unlocks_premium_features boolean not null default true,
  is_active boolean not null default true,
  description text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.subscription_credit_bundles enable row level security;
drop policy if exists "public can read active bundles" on public.subscription_credit_bundles;
create policy "public can read active bundles"
on public.subscription_credit_bundles
for select to anon, authenticated
using (is_active=true);

